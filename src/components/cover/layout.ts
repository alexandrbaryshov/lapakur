/**
 * Рамка-подсказка: силуэт пуделя, помпон которого чуть заходит на нижнюю половину заглавных шапки.
 * head — середина головы под помпоном: сюда встаёт голова питомца (и фотоаппарат на рамке-приглашении —
 * ниже строки с датой номера).
 */
export const GUIDE = (() => {
  const top = MASTHEAD.capTop + MASTHEAD.capHeight * 0.58;
  return { top, head: { x: 536 + SKETCH_SHIFT_X, y: 310 - SKETCH_TOP + top } };
})();

/** Контур рамки-подсказки (SVG-путь) из эскиза пуделя. */
export function guidePath(): string {
  const f = (n: number) => Math.round(n * 10) / 10;
  const at = ([x, y]: Pt) => `${f(x + SKETCH_SHIFT_X)} ${y === FLOOR ? COVER_H : f(y - SKETCH_TOP + GUIDE.top)}`;
  return [`M${at(POODLE_START)}`, ...POODLE.map(([c1, c2, end]) => `C${at(c1)} ${at(c2)} ${at(end)}`), "Z"].join(" ");
}

/** Поля строк обложки: левая и правая колонки у краёв кадра, по бокам от головы пуделя (морда — слева). */
