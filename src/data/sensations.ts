// на рамке-приглашении — тоже случайная (после гидрации).

import { COVER_SAMPLE_SENSATION } from "./cover";

/** Кричащие сенсации номера. */
export const COVER_SENSATIONS: readonly string[] = [
  COVER_SAMPLE_SENSATION,
  "Элегантность не лает",
  "Лапы, жемчуг и характер",
  "Икона стиля этого сезона",
  "Сенсация: идеальная укладка без фильтров",
  "Все взгляды — на эту чёлку",
  "Шерсть, которой завидуют Чебоксары",
  "Шок! Гладить только по записи",
  "Красота требует лакомств",
  "Эксклюзив: секрет блеска раскрыт",
  "Хвост трубой — главный тренд сезона",
  "Папарацци охотятся за этим хвостом",
  "Скандал! Пушистость превысила все нормы",
  "Спа, сон и лакомства: режим звезды",
  "Взгляд, который стоит миллион",
];

/** Случайная сенсация, не совпадающая с текущей (кнопка «Другая сенсация»). */
export function pickSensation(current?: string, random: () => number = Math.random): string {
  const pool = COVER_SENSATIONS.filter((s) => s !== current);
  return pool[Math.floor(random() * pool.length) % pool.length];
}
